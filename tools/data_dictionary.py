#!/usr/bin/env python3
"""Builds docs/database/data-dictionary.md from the Flyway migrations.

The dictionary is generated so it can never drift from the schema that actually ships.
Run: python3 tools/data_dictionary.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MIGRATIONS = os.path.join(ROOT, "backend", "src", "main", "resources", "db", "migration")
OUT = os.path.join(ROOT, "docs", "database", "data-dictionary.md")
SKIP = {"PRIMARY", "UNIQUE", "KEY", "CONSTRAINT", "INDEX"}

tables = []
for fname in sorted(os.listdir(MIGRATIONS)):
    src = open(os.path.join(MIGRATIONS, fname), encoding="utf-8").read()
    for match in re.finditer(r"CREATE TABLE (\w+) \((.*?)\n\) ENGINE", src, re.S):
        name, body = match.group(1), match.group(2)
        columns, keys = [], []
        for line in body.splitlines():
            stripped = line.strip().rstrip(",")
            if not stripped or stripped.startswith("--"):
                continue
            head = stripped.split()[0]
            if head in SKIP:
                keys.append(stripped)
            else:
                parts = stripped.split()
                if len(parts) >= 2:
                    columns.append((parts[0], " ".join(parts[1:]), fname))
        tables.append((name, fname, columns, keys))


def anchor(name):
    return name.replace("_", "-")


lines = [
    "# Data dictionary",
    "",
    "Generated by `tools/data_dictionary.py` from the Flyway migrations — do not edit by hand.",
    f"Tables: **{len(tables)}**. All identifiers are UUID values stored as `CHAR(36)`/`VARCHAR(36)`;",
    "all timestamps are UTC `DATETIME(6)`; money is `DECIMAL` (never floating point);",
    "`row_version` is the JPA optimistic-locking column.",
    "",
    "## Table index",
    "",
]
for name, fname, columns, _keys in tables:
    lines.append(f"- [`{name}`](#{anchor(name)}) — {len(columns)} columns · `{fname}`")
lines.append("")

for name, fname, columns, keys in tables:
    lines += ["", f"## {name}", "", f"Defined in `{fname}`.", "",
              "| Column | Definition |", "|---|---|"]
    for column, definition, _ in columns:
        lines.append(f"| `{column}` | {definition} |")
    if keys:
        lines += ["", "**Keys and constraints**", ""]
        for key in keys:
            lines.append(f"- `{key}`")
lines.append("")
open(OUT, "w", encoding="utf-8").write("\n".join(lines))
print(f"wrote {OUT} with {len(tables)} tables")
