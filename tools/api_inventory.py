#!/usr/bin/env python3
"""Generates docs/api/endpoint-inventory.md straight from the controllers.

The inventory is derived from source, so it cannot drift from the implemented API. It is the
authoritative list of what the backend actually exposes; docs/api/API-SPECIFICATION.md holds the
conventions and the intended contract.

Run: python3 tools/api_inventory.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "backend", "src", "main", "java")
OUT = os.path.join(ROOT, "docs", "api", "endpoint-inventory.md")

MAPPING = re.compile(r'@(Get|Post|Patch|Put|Delete)Mapping(?:\(\s*(?:value\s*=\s*)?(?:"([^"]*)")?)?')
rows = []

for base, _dirs, names in os.walk(SRC):
    for name in sorted(names):
        if not name.endswith(".java"):
            continue
        path = os.path.join(base, name)
        src = open(path, encoding="utf-8").read()
        if "@RestController" not in src:
            continue
        class_path = re.search(r'@RequestMapping\("([^"]*)"\)', src)
        prefix = class_path.group(1) if class_path else ""
        tag = re.search(r'@Tag\(name\s*=\s*"([^"]*)"', src)
        package = re.search(r"package\s+([\w.]+);", src).group(1)
        for match in MAPPING.finditer(src):
            method, sub = match.group(1).upper(), (match.group(2) or "")
            start = match.end()
            # the handler signature follows within the next ~400 chars
            window = src[start:start + 600]
            signature = re.search(r"public\s+[^;{]*?\s(\w+)\s*\(", window, re.S)
            handler = signature.group(1) if signature else "?"
            cap = re.search(r'capabilities?\.require(?:Any)?\([^,]+,\s*"([\w.]+)"', window)
            rows.append({
                "path": (prefix + sub) or "/",
                "method": method,
                "handler": handler,
                "module": tag.group(1) if tag else package.split(".")[-1],
                "capability": cap.group(1) if cap else "—",
                "file": os.path.relpath(path, SRC),
            })

rows.sort(key=lambda r: (r["path"], r["method"]))
lines = [
    "# Endpoint inventory (generated)",
    "",
    "Generated by `tools/api_inventory.py` from `@RestController` sources — do not edit by hand.",
    f"Endpoints: **{len(rows)}** · Controllers: **{len({r['file'] for r in rows})}**",
    "",
    "| Method | Path | Handler | Module | Capability |",
    "|---|---|---|---|---|",
]
for row in rows:
    lines.append(f"| `{row['method']}` | `{row['path']}` | `{row['handler']}` | {row['module']} | `{row['capability']}` |")

lines += ["", "## Implementation files", ""]
for file in sorted({r["file"] for r in rows}):
    lines.append(f"- `{file}`")
lines.append("")
open(OUT, "w", encoding="utf-8").write("\n".join(lines))
print(f"wrote {OUT}: {len(rows)} endpoints")
