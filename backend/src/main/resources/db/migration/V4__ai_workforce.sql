-- V5 — AI provider management, agent workforce, executions, approvals
-- =====================================================================

CREATE TABLE ai_providers (
    id                  CHAR(36)      NOT NULL,
    workspace_id        CHAR(36)      NOT NULL,
    provider_code       VARCHAR(40)   NOT NULL,
    label               VARCHAR(120)  NOT NULL,
    base_url            VARCHAR(400)  NOT NULL,
    api_key_ciphertext  VARCHAR(4096) NULL,
    key_version         INT           NOT NULL DEFAULT 1,
    default_model       VARCHAR(120)  NOT NULL,
    allowed_models      VARCHAR(1000) NULL,
    status              VARCHAR(20)   NOT NULL DEFAULT 'PENDING_TEST',
    monthly_budget_usd  DECIMAL(12,2) NOT NULL DEFAULT 100.00,
    max_requests_per_minute INT       NOT NULL DEFAULT 60,
    timeout_ms          INT           NOT NULL DEFAULT 30000,
    max_retries         INT           NOT NULL DEFAULT 2,
    last_health_at      DATETIME(6)   NULL,
    last_health_detail  VARCHAR(1000) NULL,
    created_by          CHAR(36)      NULL,
    created_at          DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at          DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at          DATETIME(6)   NULL,
    row_version         BIGINT        NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_provider (workspace_id, provider_code, label),
    CONSTRAINT fk_ai_provider_ws FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
    CONSTRAINT ck_ai_provider_status CHECK (status IN ('PENDING_TEST','ACTIVE','DISABLED','ERROR')),
    CONSTRAINT ck_ai_provider_code CHECK (provider_code IN ('OPENROUTER','OPENAI','GITHUB_COPILOT'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ai_agents (
    id                    CHAR(36)      NOT NULL,
    workspace_id          CHAR(36)      NOT NULL,
    agent_code            VARCHAR(60)   NOT NULL,
    name                  VARCHAR(160)  NOT NULL,
    purpose               VARCHAR(1000) NOT NULL,
    status                VARCHAR(20)   NOT NULL DEFAULT 'DISABLED',
    active_version        INT           NULL,
    requires_approval     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at            DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at            DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    row_version           BIGINT        NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_agent_code (workspace_id, agent_code),
    CONSTRAINT fk_ai_agent_ws FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
    CONSTRAINT ck_ai_agent_status CHECK (status IN ('DISABLED','ENABLED','PAUSED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ai_agent_versions (
    id                    CHAR(36)      NOT NULL,
    workspace_id          CHAR(36)      NOT NULL,
    agent_id              CHAR(36)      NOT NULL,
    version               INT           NOT NULL,
    provider_id           CHAR(36)      NULL,
    model                 VARCHAR(120)  NULL,
    instructions          MEDIUMTEXT    NOT NULL,
    output_schema_json    JSON          NOT NULL,
    allowed_tools_json    JSON          NOT NULL,
    data_scope_json       JSON          NOT NULL,
    max_input_tokens      INT           NOT NULL DEFAULT 12000,
    max_output_tokens     INT           NOT NULL DEFAULT 2000,
    max_tokens_per_day    BIGINT        NOT NULL DEFAULT 500000,
    max_cost_per_day_usd  DECIMAL(10,2) NOT NULL DEFAULT 10.00,
    max_executions_per_hour INT         NOT NULL DEFAULT 200,
    timeout_seconds       INT           NOT NULL DEFAULT 60,
    max_retries           INT           NOT NULL DEFAULT 1,
    temperature           DECIMAL(3,2)  NOT NULL DEFAULT 0.20,
    status                VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    created_by            CHAR(36)      NULL,
    created_at            DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    approved_by           CHAR(36)      NULL,
    approved_at           DATETIME(6)   NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_agent_version (agent_id, version),
    CONSTRAINT fk_ai_agent_version_agent FOREIGN KEY (agent_id) REFERENCES ai_agents (id) ON DELETE CASCADE,
    CONSTRAINT fk_ai_agent_version_provider FOREIGN KEY (provider_id) REFERENCES ai_providers (id),
    CONSTRAINT ck_ai_agent_version_status CHECK (status IN ('DRAFT','ACTIVE','ARCHIVED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ai_executions (
    id                    CHAR(36)      NOT NULL,
    workspace_id          CHAR(36)      NOT NULL,
    agent_id              CHAR(36)      NOT NULL,
    agent_version_id      CHAR(36)      NOT NULL,
    provider_code         VARCHAR(40)   NOT NULL,
    model                 VARCHAR(120)  NOT NULL,
    trigger_type          VARCHAR(40)   NOT NULL,
    related_type          VARCHAR(30)   NULL,
    related_id            CHAR(36)      NULL,
    status                VARCHAR(30)   NOT NULL DEFAULT 'QUEUED',
    input_json            JSON          NOT NULL,
    input_tokens          INT           NULL,
    output_tokens         INT           NULL,
    cost_usd              DECIMAL(10,4) NULL,
    output_json           JSON          NULL,
    schema_valid          BOOLEAN       NULL,
    raw_output            MEDIUMTEXT    NULL,
    error_code            VARCHAR(60)   NULL,
    error_detail          VARCHAR(2000) NULL,
    attempt_count         INT           NOT NULL DEFAULT 0,
    latency_ms            INT           NULL,
    requested_by          CHAR(36)      NULL,
    created_at            DATETIME(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    started_at            DATETIME(6)   NULL,
    finished_at           DATETIME(6)   NULL,
    PRIMARY KEY (id),
    KEY idx_ai_exec_status (workspace_id, status, created_at),
    KEY idx_ai_exec_agent (agent_id, created_at),
    KEY idx_ai_exec_related (related_type, related_id),
    CONSTRAINT fk_ai_exec_ws FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
    CONSTRAINT fk_ai_exec_agent FOREIGN KEY (agent_id) REFERENCES ai_agents (id),
    CONSTRAINT ck_ai_exec_status CHECK (status IN ('QUEUED','RUNNING','SUCCEEDED','FAILED','WAITING_FOR_APPROVAL',
        'APPROVED','REJECTED','EXECUTED','EXPIRED','CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ai_execution_tool_calls (
    id                CHAR(36)     NOT NULL,
    workspace_id      CHAR(36)     NOT NULL,
    execution_id      CHAR(36)     NOT NULL,
    tool_name         VARCHAR(80)  NOT NULL,
    arguments_json    JSON         NULL,
    result_json       JSON         NULL,
    allowed           BOOLEAN      NOT NULL DEFAULT TRUE,
    blocked_reason    VARCHAR(400) NULL,
    duration_ms       INT          NULL,
    occurred_at       DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_ai_tool_exec (execution_id),
    CONSTRAINT fk_ai_tool_exec FOREIGN KEY (execution_id) REFERENCES ai_executions (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ai_usage_daily (
    id                CHAR(36)      NOT NULL,
    workspace_id      CHAR(36)      NOT NULL,
    usage_date        DATE          NOT NULL,
    provider_code     VARCHAR(40)   NOT NULL,
    model             VARCHAR(120)  NOT NULL,
    requests          INT           NOT NULL DEFAULT 0,
    input_tokens      BIGINT        NOT NULL DEFAULT 0,
    output_tokens     BIGINT        NOT NULL DEFAULT 0,
    cost_usd          DECIMAL(12,4) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_usage (workspace_id, usage_date, provider_code, model)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE approvals (
    id                    CHAR(36)     NOT NULL,
    workspace_id          CHAR(36)     NOT NULL,
    approval_type         VARCHAR(40)  NOT NULL,
    object_type           VARCHAR(40)  NOT NULL,
    object_id             CHAR(36)     NOT NULL,
    payload_hash          CHAR(64)     NOT NULL,
    object_version        BIGINT       NOT NULL,
    policy_version        VARCHAR(40)  NOT NULL,
    status                VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    requested_by          CHAR(36)     NULL,
    requested_at          DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    decided_by            CHAR(36)     NULL,
    decided_at            DATETIME(6)  NULL,
    decision_note         VARCHAR(1000) NULL,
    expires_at            DATETIME(6)  NULL,
    consumed_at           DATETIME(6)  NULL,
    summary               VARCHAR(2000) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_approvals_pending (workspace_id, status, requested_at),
    KEY idx_approvals_object (object_type, object_id),
    CONSTRAINT fk_approvals_ws FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
    CONSTRAINT ck_approvals_status CHECK (status IN ('PENDING','APPROVED','REJECTED','EXPIRED','CONSUMED','CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
