package com.infeara.sales.engagement.mailbox;

import java.time.Instant;
import java.util.List;
import java.util.Map;

/**
 * Provider-neutral representation of one fetched message (addendum 3.2). The IMAP connector, and any
 * future Gmail/Graph adapter, produce this and nothing else: everything downstream is provider
 * agnostic.
 */
public record ParsedEmail(
        String providerMessageId,
        String rfcMessageId,
        String inReplyTo,
        String references,
        String fromEmail,
        String fromName,
        String toEmail,
        List<String> ccEmails,
        String replyToEmail,
        String subject,
        Instant receivedAt,
        String textBody,
        String htmlBody,
        Map<String, String> rawHeaders,
        Long uid,
        Long uidValidity,
        List<ParsedAttachment> attachments) {

    public record ParsedAttachment(String filename, String mediaType, long sizeBytes, String sha256) {
    }

    /** True when the message announces itself as machine generated (loop prevention, addendum 7). */
    public boolean isAutoGenerated() {
        String autoSubmitted = header("auto-submitted");
        String precedence = header("precedence");
        String autoReply = header("x-autoreply");
        String autoReply2 = header("x-autorespond");
        return (autoSubmitted != null && !"no".equalsIgnoreCase(autoSubmitted))
                || (precedence != null && ("bulk".equalsIgnoreCase(precedence)
                        || "junk".equalsIgnoreCase(precedence) || "list".equalsIgnoreCase(precedence)))
                || "yes".equalsIgnoreCase(autoReply)
                || autoReply2 != null;
    }

    public String header(String name) {
        if (rawHeaders == null || name == null) {
            return null;
        }
        for (Map.Entry<String, String> entry : rawHeaders.entrySet()) {
            if (entry.getKey().equalsIgnoreCase(name)) {
                return entry.getValue();
            }
        }
        return null;
    }
}
