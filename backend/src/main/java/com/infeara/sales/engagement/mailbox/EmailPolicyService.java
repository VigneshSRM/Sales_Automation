package com.infeara.sales.engagement.mailbox;

import com.infeara.sales.common.json.JsonCodec;
import java.math.BigDecimal;
import java.time.Clock;
import java.time.DayOfWeek;
import java.time.LocalTime;
import java.time.ZonedDateTime;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * Response policy engine (addendum 3.4).
 *
 * <p>Order of evaluation matters and is deliberate:
 * <ol>
 *   <li>loop/auto-generated detection → {@code NO_RESPONSE} (never answer a robot);</li>
 *   <li>intents that are never auto-answered (unsubscribe, bounce, out-of-office, spam) →
 *       {@code NO_RESPONSE};</li>
 *   <li>sensitive intents (complaint, negotiation, pricing, proposals) can never be
 *       {@code AUTOMATIC} — they cap at {@code APPROVAL_REQUIRED};</li>
 *   <li>configured rules, highest priority first, subject to their confidence threshold;</li>
 *   <li>anything unmatched, low-confidence, or arriving outside business hours is human-handled.</li>
 * </ol>
 */
@Service
public class EmailPolicyService {

    private static final Logger log = LoggerFactory.getLogger(EmailPolicyService.class);

    /** Intents that must never receive an automated reply. */
    private static final Set<String> NEVER_AUTO = Set.of("UNSUBSCRIBE", "BOUNCE", "OUT_OF_OFFICE", "SPAM");

    /** Intents that always require human approval before anything is sent. */
    private static final Set<String> APPROVAL_ONLY = Set.of("COMPLAINT", "NEGOTIATION", "OBJECTION",
            "PRICING_ENQUIRY", "PROPOSAL_REQUEST", "CUSTOMER_SUPPORT");

    private final EmailAutomationRuleRepository rules;
    private final JsonCodec jsonCodec;
    private final Clock clock;

    public EmailPolicyService(EmailAutomationRuleRepository rules, JsonCodec jsonCodec, Clock clock) {
        this.rules = rules;
        this.jsonCodec = jsonCodec;
        this.clock = clock;
    }

    public record Decision(String mode, String reasonCode, String ruleName, boolean mayAutoSend,
                           int delaySeconds) {
    }

    @Transactional(readOnly = true)
    public Decision decide(String workspaceId, String intent, BigDecimal confidence, boolean autoGenerated,
                           String accountId, String timezone) {
        if (autoGenerated) {
            return new Decision("NO_RESPONSE", "AUTO_GENERATED_MESSAGE", null, false, 0);
        }
        if (intent != null && NEVER_AUTO.contains(intent)) {
            return new Decision("NO_RESPONSE", "INTENT_NEVER_AUTO_RESPONDED", null, false, 0);
        }

        List<EmailAutomationRule> candidates = rules
                .findByWorkspaceIdAndEnabledTrueAndDeletedAtIsNullOrderByPriorityAsc(workspaceId);
        for (EmailAutomationRule rule : candidates) {
            if (rule.getAccountId() != null && accountId != null && !rule.getAccountId().equals(accountId)) {
                continue;
            }
            if (!intentAllowed(rule, intent)) {
                continue;
            }
            BigDecimal threshold = rule.getMinConfidence() == null ? new BigDecimal("0.85")
                    : rule.getMinConfidence();
            if (confidence == null || confidence.compareTo(threshold) < 0) {
                continue;
            }
            if (APPROVAL_ONLY.contains(intent) && "AUTOMATIC".equals(rule.getMode())) {
                return new Decision("APPROVAL_REQUIRED", "SENSITIVE_INTENT_REQUIRES_APPROVAL", rule.getName(),
                        false, rule.getDelaySeconds());
            }
            if ("AUTOMATIC".equals(rule.getMode()) && !withinBusinessHours(rule, timezone)) {
                return new Decision("APPROVAL_REQUIRED", "OUTSIDE_BUSINESS_HOURS", rule.getName(), false,
                        rule.getDelaySeconds());
            }
            log.debug("email_policy_rule_applied rule={} mode={}", rule.getName(), rule.getMode());
            return new Decision(rule.getMode(), "RULE_MATCHED", rule.getName(),
                    "AUTOMATIC".equals(rule.getMode()), rule.getDelaySeconds());
        }

        if (intent == null || confidence == null) {
            return new Decision("HUMAN", "NO_VALIDATED_ANALYSIS", null, false, 0);
        }
        if (APPROVAL_ONLY.contains(intent)) {
            return new Decision("APPROVAL_REQUIRED", "SENSITIVE_INTENT_REQUIRES_APPROVAL", null, false, 0);
        }
        return new Decision("HUMAN", "NO_RULE_MATCHED", null, false, 0);
    }

    private boolean intentAllowed(EmailAutomationRule rule, String intent) {
        Set<String> blocked = readSet(rule.getBlockedIntentsJson());
        if (intent != null && blocked.contains(intent)) {
            return false;
        }
        Set<String> allowed = readSet(rule.getAllowedIntentsJson());
        return allowed.isEmpty() || (intent != null && allowed.contains(intent));
    }

    private Set<String> readSet(String json) {
        if (json == null || json.isBlank()) {
            return Set.of();
        }
        try {
            List<String> values = jsonCodec.readListOfMaps(json).stream()
                    .map(map -> String.valueOf(map.get("value")))
                    .toList();
            return new LinkedHashSet<>(values);
        } catch (RuntimeException ex) {
            try {
                List<?> raw = jsonCodec.read(json, List.class);
                Set<String> result = new LinkedHashSet<>();
                for (Object item : raw) {
                    result.add(String.valueOf(item).toUpperCase(Locale.ROOT));
                }
                return result;
            } catch (RuntimeException ignored) {
                return Set.of();
            }
        }
    }

    /**
     * Business hours are stored as {@code {"days":["MONDAY",...],"start":"09:00","end":"18:00"}}.
     * A rule without hours is always in hours.
     */
    private boolean withinBusinessHours(EmailAutomationRule rule, String timezone) {
        if (rule.getBusinessHoursJson() == null || rule.getBusinessHoursJson().isBlank()) {
            return true;
        }
        try {
            Map<String, Object> hours = jsonCodec.readMap(rule.getBusinessHoursJson());
            ZonedDateTime now = ZonedDateTime.now(clock.withZone(java.time.ZoneId.of(
                    timezone == null ? "UTC" : timezone)));
            Object days = hours.get("days");
            if (days instanceof List<?> list && !list.isEmpty()) {
                DayOfWeek today = now.getDayOfWeek();
                boolean dayMatch = list.stream().anyMatch(day -> String.valueOf(day).equalsIgnoreCase(today.name()));
                if (!dayMatch) {
                    return false;
                }
            }
            LocalTime start = LocalTime.parse(String.valueOf(hours.getOrDefault("start", "00:00")));
            LocalTime end = LocalTime.parse(String.valueOf(hours.getOrDefault("end", "23:59")));
            LocalTime local = now.toLocalTime();
            return !local.isBefore(start) && !local.isAfter(end);
        } catch (RuntimeException ex) {
            log.warn("email_policy_business_hours_invalid rule={}", rule.getName());
            return false;
        }
    }
}
