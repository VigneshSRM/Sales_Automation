#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Hosts the application on Apache Tomcat 11:
#   1. provisions the MariaDB database + application user (no superuser in the app)
#   2. writes Tomcat's setenv.sh from deploy/tomcat/setenv.sh with the deployment's secrets
#   3. deploys the single WAR as ROOT.war (UI and API on one origin)
#   4. starts Tomcat and waits for a real HTTP 200 from /actuator/health
#
#   sudo ./scripts/host-app.sh
#
# Re-running is safe: migrations are idempotent (Flyway), the WAR is replaced and
# Tomcat hot-redeploys the context.
# ---------------------------------------------------------------------------
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIST_WAR="$ROOT_DIR/dist/infeara-sales-os.war"
CATALINA_HOME="${CATALINA_HOME:-/opt/infeara/tomcat}"
CATALINA_BASE="${CATALINA_BASE:-$CATALINA_HOME}"
LOG_DIR="${CATALINA_BASE}/logs"

log() { printf '\033[1;34m[host-app]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[host-app]\033[0m %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Run as root: sudo $0"
[ -f "$DIST_WAR" ] || die "dist/infeara-sales-os.war not found — run ./scripts/build-war.sh first"
[ -x "$CATALINA_HOME/bin/catalina.sh" ] || die "Tomcat not found at $CATALINA_HOME — run ./scripts/install-toolchain.sh"

# ---------------------------------------------------------------- configuration
: "${DB_NAME:=infeara_sales}"
: "${DB_USER:=infeara}"
: "${DB_PASSWORD:=$(openssl rand -base64 24 | tr -d '\n')}"
: "${APP_BASE_URL:=http://localhost:8080}"
: "${BOOTSTRAP_ADMIN_EMAIL:=admin@infeara.local}"
: "${BOOTSTRAP_ADMIN_PASSWORD:=$(openssl rand -base64 18 | tr -d '\n')}"
: "${SMTP_SECRET_ENCRYPTION_KEY:=$(openssl rand -base64 32)}"

log "Provisioning MariaDB database '$DB_NAME' and user '$DB_USER'"
mariadb --protocol=socket -uroot <<SQL
CREATE DATABASE IF NOT EXISTS \`${DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${DB_USER}'@'localhost' IDENTIFIED BY '${DB_PASSWORD}';
ALTER USER '${DB_USER}'@'localhost' IDENTIFIED BY '${DB_PASSWORD}';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON \`${DB_NAME}\`.* TO '${DB_USER}'@'localhost';
FLUSH PRIVILEGES;
SQL
log "Database ready (the application user has DML + DDL, no GRANT/CREATE USER)"

# ---------------------------------------------------------------- Tomcat env
log "Writing $CATALINA_BASE/bin/setenv.sh"
cat > "$CATALINA_BASE/bin/setenv.sh" <<SETENV
#!/bin/sh
# Generated by scripts/host-app.sh — contains deployment secrets, mode 0750, never in git.
export JAVA_HOME="\${JAVA_HOME:-$(dirname "$(dirname "$(readlink -f "$(command -v javac)")")")}"
export CATALINA_OPTS="\${CATALINA_OPTS} -Xms512m -Xmx1536m -XX:+UseG1GC -Dfile.encoding=UTF-8"
# Names must match application.yml exactly (DB_HOST/DB_PORT/DB_NAME/DB_USER/DB_PASSWORD).
export DB_HOST="127.0.0.1"
export DB_PORT="3306"
export DB_NAME="${DB_NAME}"
export DB_USER="${DB_USER}"
export DB_PASSWORD="${DB_PASSWORD}"
export APP_BASE_URL="${APP_BASE_URL}"
export APP_ENV="production"
export SMTP_SECRET_ENCRYPTION_KEY="${SMTP_SECRET_ENCRYPTION_KEY}"
export SMTP_SECRET_ENCRYPTION_KEY_ID="k1"
export BOOTSTRAP_WORKSPACE_NAME="Infeara Technologies"
export BOOTSTRAP_WORKSPACE_SLUG="infeara"
export BOOTSTRAP_ADMIN_EMAIL="${BOOTSTRAP_ADMIN_EMAIL}"
export BOOTSTRAP_ADMIN_PASSWORD="${BOOTSTRAP_ADMIN_PASSWORD}"
# Inbound mail + AI are optional; the UI states plainly when they are not configured.
export EMAIL_INBOUND_DISCOVERY_INTERVAL_MS="60000"
export WORKER_ENABLED="true"
SETENV
chmod 0750 "$CATALINA_BASE/bin/setenv.sh"

# ---------------------------------------------------------------- deploy
log "Deploying ROOT.war (single WAR: API + UI, one origin, no CORS)"
mkdir -p "$CATALINA_BASE/webapps"
rm -rf "$CATALINA_BASE/webapps/ROOT" "$CATALINA_BASE/webapps/ROOT.war"
cp "$DIST_WAR" "$CATALINA_BASE/webapps/ROOT.war"

if pgrep -f "catalina.base=$CATALINA_BASE" >/dev/null 2>&1; then
  log "Stopping the running Tomcat instance"
  "$CATALINA_HOME/bin/shutdown.sh" 10 -force >/dev/null 2>&1 || true
  sleep 3
fi

log "Starting Tomcat"
mkdir -p "$LOG_DIR"
"$CATALINA_HOME/bin/startup.sh" >/dev/null

log "Waiting for /actuator/health to report UP"
for attempt in $(seq 1 60); do
  if curl -fsS -o /tmp/health.json "http://localhost:8080/actuator/health" 2>/dev/null; then
    if grep -q '"status":"UP"' /tmp/health.json; then
      log "Application is UP after ${attempt}s"
      break
    fi
  fi
  if [ "$attempt" -eq 60 ]; then
    echo "----- catalina.out (tail) -----" >&2
    tail -n 80 "$LOG_DIR/catalina.out" >&2 || true
    die "Tomcat did not become healthy; see $LOG_DIR/catalina.out"
  fi
  sleep 1
done

log "Smoke checks"
code_ui="$(curl -s -o /dev/null -w '%{http_code}' http://localhost:8080/)"
code_api="$(curl -s -o /dev/null -w '%{http_code}' http://localhost:8080/api/v1/auth/me)"
log "UI  /                -> HTTP $code_ui  (200 expected: login page)"
log "API /api/v1/auth/me  -> HTTP $code_api  (401 expected: unauthenticated)"
[ "$code_ui" = "200" ] || die "The UI is not being served by Tomcat"

cat <<SUMMARY

  Infeara Sales OS is hosted on Apache Tomcat 11
  ---------------------------------------------------------------
  UI and API : ${APP_BASE_URL}          (same WAR, same origin)
  OpenAPI    : ${APP_BASE_URL}/swagger-ui.html
  Health     : ${APP_BASE_URL}/actuator/health
  Logs       : ${LOG_DIR}/catalina.out

  Sign in    : ${BOOTSTRAP_ADMIN_EMAIL}
  Password   : ${BOOTSTRAP_ADMIN_PASSWORD}
  (recorded only in ${CATALINA_BASE}/bin/setenv.sh, mode 0750)

  Next: connect an SMTP profile (Sending accounts), then a mailbox
  (Mailbox connections) and run Test before enabling inbound sync.
SUMMARY
